void InterpolateLqrGain(double leg_length, double gain[2][6]) {
  constexpr int count = sizeof(kGainTable) / sizeof(kGainTable[0]);
  const double scheduled = std::clamp(
      leg_length, kGainTable[0].leg_length, kGainTable[count - 1].leg_length);
  int upper = 1;
  while (upper < count - 1 && scheduled > kGainTable[upper].leg_length) {
    ++upper;
  }
  const LqrGainNode& lower_node = kGainTable[upper - 1];
  const LqrGainNode& upper_node = kGainTable[upper];
  const double alpha = (scheduled - lower_node.leg_length) /
      (upper_node.leg_length - lower_node.leg_length);
  for (int input = 0; input < 2; ++input) {
    for (int state = 0; state < 6; ++state) {
      gain[input][state] = lower_node.gain[input][state] + alpha *
          (upper_node.gain[input][state] - lower_node.gain[input][state]);
    }
  }
}

